/* =========================================================================
   2. GEOGRAPHIC UTILITY FUNCTIONS
   ========================================================================= */

const DEG = Math.PI / 180;
const RAD = 180 / Math.PI;
const EARTH_DEG_KM = 111.32; // km per degree of latitude (mean)

/** Ray casting. ring = [[lon, lat], ...]. Returns true if the point is inside. */
function pointInPolygon(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const xi = ring[i][0], yi = ring[i][1];
    const xj = ring[j][0], yj = ring[j][1];
    const intersects =
      (yi > lat) !== (yj > lat) &&
      lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;
    if (intersects) inside = !inside;
  }
  return inside;
}

/** Bounding box over one or more rings: { minLon, minLat, maxLon, maxLat }. */
function getBoundingBox(polygons) {
  let minLon = Infinity, minLat = Infinity, maxLon = -Infinity, maxLat = -Infinity;
  for (const ring of polygons) {
    for (const [lon, lat] of ring) {
      if (lon < minLon) minLon = lon;
      if (lon > maxLon) maxLon = lon;
      if (lat < minLat) minLat = lat;
      if (lat > maxLat) maxLat = lat;
    }
  }
  return { minLon, minLat, maxLon, maxLat };
}

function boxContains(box, lon, lat) {
  return lon >= box.minLon && lon <= box.maxLon && lat >= box.minLat && lat <= box.maxLat;
}

/** Shoelace area, corrected by cos(latitude) so it approximates km². */
function approximateAreaKm2(ring) {
  let latSum = 0;
  for (const p of ring) latSum += p[1];
  const cosLat = Math.cos((latSum / ring.length) * DEG);
  let sum = 0;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    sum += (ring[j][0] * ring[i][1] - ring[i][0] * ring[j][1]);
  }
  const areaDeg2 = Math.abs(sum) / 2;
  return areaDeg2 * EARTH_DEG_KM * EARTH_DEG_KM * Math.abs(cosLat);
}

/** Pre-computed geometry. Built once at module load, never inside a render. */
const GEO = COUNTRIES.map((country) => {
  const rings = country.polygons.map((points) => ({
    points,
    bbox: getBoundingBox([points]),
    area: Math.max(approximateAreaKm2(points), 0.0001),
  }));
  const area = rings.reduce((acc, r) => acc + r.area, 0);
  return {
    code: country.code,
    name: country.name,
    search: (country.name + " " + country.code).toLowerCase(),
    rings,
    bbox: getBoundingBox(country.polygons),
    area,
  };
}).sort((a, b) => a.name.localeCompare(b.name));

const COUNTRIES_BY_CODE = GEO.reduce((acc, c) => {
  acc[c.code] = c;
  return acc;
}, {});

/** True if the point falls inside any polygon of the country. */
function countryContains(country, lon, lat) {
  if (!boxContains(country.bbox, lon, lat)) return false;
  for (const ring of country.rings) {
    if (!boxContains(ring.bbox, lon, lat)) continue;
    if (pointInPolygon(lon, lat, ring.points)) return true;
  }
  return false;
}

/** First country containing the point, or null (ocean / not covered). */
function locateCountry(lon, lat) {
  for (const country of GEO) {
    if (countryContains(country, lon, lat)) return country;
  }
  return null;
}

/* =========================================================================
   3. RANDOM GENERATION ALGORITHMS
   ========================================================================= */

const MAX_POLYGON_TRIES = 400;
const MAX_EXCLUDE_TRIES = 20000;
const MAX_OCEAN_TRIES = 20000;

/** Uniform on the sphere: latitude drawn through asin, not linearly. */
function randomWorldPoint() {
  const lon = Math.random() * 360 - 180;
  const u = Math.random() * 2 - 1;
  const lat = Math.asin(u) * RAD;
  return { lat, lon };
}

/** Uniform-on-sphere sampling restricted to a bounding box. */
function randomPointInBox(box) {
  const lon = box.minLon + Math.random() * (box.maxLon - box.minLon);
  const sinMin = Math.sin(box.minLat * DEG);
  const sinMax = Math.sin(box.maxLat * DEG);
  const u = sinMin + Math.random() * (sinMax - sinMin);
  return { lat: Math.asin(Math.min(1, Math.max(-1, u))) * RAD, lon };
}

function pickWeighted(items, weightOf) {
  let total = 0;
  for (const item of items) total += weightOf(item);
  if (!(total > 0)) return items[Math.floor(Math.random() * items.length)];
  let r = Math.random() * total;
  for (const item of items) {
    r -= weightOf(item);
    if (r <= 0) return item;
  }
  return items[items.length - 1];
}

/** Fallback: fan triangulation from the ring centroid. Always finite. */
function fanSample(ring) {
  const pts = ring.points;
  let cx = 0, cy = 0;
  for (const p of pts) { cx += p[0]; cy += p[1]; }
  cx /= pts.length; cy /= pts.length;
  for (let attempt = 0; attempt < 200; attempt++) {
    const i = Math.floor(Math.random() * pts.length);
    const a = pts[i];
    const b = pts[(i + 1) % pts.length];
    let r1 = Math.random(), r2 = Math.random();
    if (r1 + r2 > 1) { r1 = 1 - r1; r2 = 1 - r2; }
    const lon = cx + r1 * (a[0] - cx) + r2 * (b[0] - cx);
    const lat = cy + r1 * (a[1] - cy) + r2 * (b[1] - cy);
    if (pointInPolygon(lon, lat, pts)) return { lat, lon };
  }
  return { lat: cy, lon: cx };
}

/** Reject-sample inside one ring, with a bounded number of tries. */
function randomPointInRing(ring) {
  for (let i = 0; i < MAX_POLYGON_TRIES; i++) {
    const p = randomPointInBox(ring.bbox);
    if (pointInPolygon(p.lon, p.lat, ring.points)) return p;
  }
  return fanSample(ring);
}

/** INCLUDE: country picked first, then polygon weighted by approximate area. */
function randomPointInCountries(countries, distribution) {
  if (!countries.length) return null;
  const country =
    distribution === "area"
      ? pickWeighted(countries, (c) => c.area)
      : countries[Math.floor(Math.random() * countries.length)];
  const ring = pickWeighted(country.rings, (r) => r.area);
  const point = randomPointInRing(ring);
  return { ...point, country };
}

/** WORLD: uniform sphere point, optionally rerolled until it lands on land. */
function randomLandAwareWorldPoint(avoidOcean) {
  let point = randomWorldPoint();
  let country = locateCountry(point.lon, point.lat);
  if (!avoidOcean) return { ...point, country };
  for (let i = 0; i < MAX_OCEAN_TRIES && country === null; i++) {
    point = randomWorldPoint();
    country = locateCountry(point.lon, point.lat);
  }
  return { ...point, country };
}

/** EXCLUDE: uniform world point, rerolled while blocked by an excluded country
 *  or (when avoidOcean is set) while it lands in the ocean. */
function randomPointOutsideCountries(countries, avoidOcean) {
  const maxTries = countries.length || avoidOcean ? MAX_EXCLUDE_TRIES : 1;
  let point = randomWorldPoint();
  let country = locateCountry(point.lon, point.lat);
  for (let i = 0; i < maxTries; i++) {
    let blocked = false;
    for (const c of countries) {
      if (countryContains(c, point.lon, point.lat)) { blocked = true; break; }
    }
    if (!blocked && !(avoidOcean && country === null)) return { ...point, country };
    point = randomWorldPoint();
    country = locateCountry(point.lon, point.lat);
  }
  return { ...point, country };
}

function formatCoordinate(value) {
  if (!Number.isFinite(value)) return "0.000000";
  return value.toFixed(6);
}

